    mk_archive "$tmp/arch-venv" cuda12
    vfv=$tmp/arch-venv/bin/vf
    ve="$tmp/an env"
    "$vfv" venv "$ve" -- --without-pip >/dev/null 2>&1 || true
    sp=$(ls -d "$ve"/lib/python*/site-packages 2>/dev/null | head -1)

    name="venv-made"
    if [ -x "$ve/bin/python" ] && [ -f "$sp/volta_forever.pth" ] && [ -f "$sp/volta_forever_venv.py" ] \
        && [ "$(cat "$sp/volta_forever_venv.path")" = "$vfv" ]; then
        pass "$name"
    else
        fail "$name" "the environment or its hook is not there"
    fi

    name="venv-python-through-the-layer"
    got=$("$ve/bin/python" -c 'import os; print(os.environ.get("VOLTA_FOREVER"), os.environ.get("VOLTA_FOREVER_HOME"), os.environ.get("LD_AUDIT"))')
    if [ "$got" = "0.1.0 $tmp/arch-venv $tmp/arch-venv/lib/libvf_audit.so" ]; then
        pass "$name"
    else
        fail "$name" "its Python saw: $got"
    fi

    name="venv-arguments"
    got=$("$ve/bin/python" -c 'import sys; print("|".join(sys.argv[1:]))' 'a b' '' "it's")
    if [ "$got" = "a b||it's" ]; then pass "$name"; else fail "$name" "arguments: $got"; fi

    name="venv-exit-status"
    _vstat=0
    "$ve/bin/python" -c 'raise SystemExit(7)' || _vstat=$?
    if [ "$_vstat" = 7 ]; then pass "$name"; else fail "$name" "status: $_vstat"; fi

    name="venv-standard-input"
    got=$(echo 'print(6 * 7)' | "$ve/bin/python" -)
    if [ "$got" = 42 ]; then pass "$name"; else fail "$name" "printed: $got"; fi

    name="venv-child"
    got=$("$ve/bin/python" -c 'import subprocess, sys; print(subprocess.run([sys.executable, "-c", "import os; print(os.environ.get(\"VOLTA_FOREVER\"))"], capture_output=True, text=True).stdout.strip())')
    if [ "$got" = "0.1.0" ]; then pass "$name"; else fail "$name" "a child Python saw: $got"; fi

    name="venv-off-for-one-command"
    got=$(VF_VENV=0 "$ve/bin/python" -c 'import os; print(os.environ.get("VOLTA_FOREVER"))')
    if [ "$got" = None ]; then pass "$name"; else fail "$name" "with VF_VENV=0: $got"; fi

    name="venv-again"
    if "$vfv" venv "$ve" >/dev/null 2>&1 && [ "$("$ve/bin/python" -c 'import os; print(os.environ.get("VOLTA_FOREVER"))')" = "0.1.0" ]; then
        pass "$name"
    else
        fail "$name" "a second vf venv on the same directory"
    fi

    # Not a virtual environment: a Python with no pyvenv.cfg; a directory that holds something.
    name="venv-refuses-another-python"
    mkdir -p "$tmp/not-venv/bin" "$tmp/not-venv/lib"
    ln -s "$(command -v python3)" "$tmp/not-venv/bin/python"
    _vstat=0
    "$vfv" venv "$tmp/not-venv" >/dev/null 2>&1 || _vstat=$?
