# 5b. --map FILE is read as the audit library reads a file of its own: a replacement that is
# not an absolute path is in the directory of the file (wherever the launcher is called from),
# the last line counts without its end of line, an empty replacement stays empty, the white
# space around a name and a replacement goes, a line that starts with # is no entry.

name="map-file-as-a-file"
mkdir -p "$tmp/config"
printf '# a comment\n\n  libprobe.so.1 = ./libprobe.so  \nlibnone.so.1=\nliblast.so.1=/abs/last.so' >"$tmp/config/relative.map"
config=$(cd "$tmp/config" && pwd)
map=$(get_var "$vf" VF_AUDIT_MAP --map "$tmp/config/relative.map")
case $map in
    "libprobe.so.1=$config/./libprobe.so:libnone.so.1=:liblast.so.1=/abs/last.so:"*)
        pass "$name" ;;
    *)
        fail "$name" "got: $map" ;;
esac

# Rust str::trim accepts Unicode White_Space in every locale, including NBSP and NEL.
# U+001C..U+001F are ordinary filename bytes for the audit library.
name="map-file-unicode-whitespace"
padding=$(printf '\011\302\240\302\205\341\232\200\342\200\207\342\200\250\342\200\257\342\201\237\343\200\200')
controls=$(printf '\034\035\036\037')
printf '%s# comment=with:colon\n%sabs.so%s=%s/absolute.so%s\nrel.so=%srelative.so%s\n%sname%s=%sfile%s' \
    "$padding" "$padding" "$padding" "$padding" "$padding" "$padding" "$padding" \
    "$controls" "$controls" "$controls" "$controls" >"$tmp/config/unicode.map"
wanted="abs.so=/absolute.so:rel.so=$config/relative.so:${controls}name${controls}=$config/${controls}file${controls}"
for map_locale in C C.UTF-8; do
    if value=$(LC_ALL=$map_locale run_var "$vf" VF_AUDIT_MAP --map "$tmp/config/unicode.map"); then
        case $value in
            "$wanted:"*) pass "$name-$map_locale" ;;
            *) fail "$name-$map_locale" "map differs from the audit file format" ;;
        esac
    else
        fail "$name-$map_locale" "launcher rejected the map"
    fi
done

name="map-file-named-by-a-relative-path"
map2=$(cd "$tmp" && get_var "$vf" VF_AUDIT_MAP --map config/relative.map)
if [ "$map2" = "$map" ]; then
    pass "$name"
else
    fail "$name" "got: $map2"
fi

name="map-file-missing"
_st=0
err=$("$vf" --map "$tmp/no-such.map" env 2>&1 >/dev/null) || _st=$?
case "$_st:$err" in
    2:*"is not a file that can be read"*)
        pass "$name" ;;
    *)
        fail "$name" "exit $_st, said: $err" ;;
esac

# (An entry with a colon cannot go into the variable, whose entries colons separate: said, not
# passed on wrong.)
name="map-file-colon"
printf 'libx.so.1=/a:b/libx.so\n' >"$tmp/colon.map"
_st=0
err=$("$vf" --map "$tmp/colon.map" env 2>&1 >/dev/null) || _st=$?
case "$_st:$err" in
    2:*"VF_AUDIT_MAP_FILE"*)
        pass "$name" ;;
    *)
        fail "$name" "exit $_st, said: $err" ;;
esac

# 6. --no-audit: LD_AUDIT is not set.

name="no-audit"
lda=$(run_var "$vf" LD_AUDIT --no-audit)
if [ -z "$lda" ]; then
    pass "$name"
else
    fail "$name" "LD_AUDIT is set: $lda"
fi

# --no-audit takes an audit library of the layer out of an LD_AUDIT that was there (after
# eval "$(vf env)": the loader would load it all the same), and keeps the others; LD_AUDIT is
# unset when nothing is left. env says so too. (Until 2026-11-23 it was left as it was.)
name="no-audit-inherited"
lda1=$(LD_AUDIT="$arch/lib/libvf_audit.so:/my/audit.so" "$vf" --no-audit sh -c 'printf "%s" "${LD_AUDIT-unset}"')
lda2=$(LD_AUDIT="$arch/lib/libvf_audit.so" "$vf" --no-audit sh -c 'printf "%s" "${LD_AUDIT-unset}"')
lda3=$(LD_AUDIT=/my/audit.so "$vf" --no-audit sh -c 'printf "%s" "${LD_AUDIT-unset}"')
env1=$(LD_AUDIT="/other/lib/libvf_audit.so:/my/audit.so" "$vf" env --no-audit | grep LD_AUDIT || true)
env2=$(LD_AUDIT="$arch/lib/libvf_audit.so" "$vf" env --no-audit | grep LD_AUDIT || true)
