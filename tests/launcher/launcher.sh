TOML
    cp "$launcher" "$_d/scripts/vf"
    chmod +x "$_d/scripts/vf"
    ln -s vf "$_d/scripts/volta-forever"
}

# --- helpers to get environment from the launcher --------------------------------

# get_var LAUNCHER VAR [ARGS...]: run env through the launcher and extract VAR.
get_var() {
    _lnch=$1 _var=$2; shift 2
    eval "$("$_lnch" "$@" env)" 2>/dev/null
    eval 'echo "$'"$_var"'"'
}

# run_var LAUNCHER VAR [ARGS...] -- COMMAND: run a command through the launcher and
# get the value of VAR as the command sees it.
run_var() {
    _lnch=$1 _var=$2; shift 2
    "$_lnch" "$@" sh -c "printf '%s' \"\$$_var\""
}

