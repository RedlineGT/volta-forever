#!/bin/sh
# Host tests for the launcher, vf (no GPU needed):
#   tests/launcher/launcher.sh
# Creates a temporary fake installation (both archive and source-tree layouts), then
# exercises the variables that env prints and that a command run by the prefix form sees,
# the order of path entries, the map entries, priority of user map entries, a map file
# given with --map (read as the audit library reads one), --no-audit,
# --cuda12 and $VF_CUDA12, the warning when CUDA 12.9.2 is absent and its
# silencing, what is done when only some of the CUDA 12.9.2 libraries are there,
# arguments with spaces and empty arguments, the exit status, env applied
# twice, a symlinked launcher, doctor exit status, fetch command line, help and unknown
# options. Prints PASS/FAIL per case; exits 1 on a failure.
set -eu

W=$(cd "$(dirname "$0")/../.." && pwd)
launcher=$W/scripts/vf
[ -x "$launcher" ] || { echo "missing: $launcher"; exit 2; }

tmp=$(mktemp -d "${TMPDIR:-/tmp}/vf-launcher-test.XXXXXX") || exit 2
# (The audit library of the fake installations is an empty file: the loader says so on standard
# error for every command that the launcher runs. Those lines are left out of what is shown.)
exec 3>&2 2>"$tmp/stderr"
trap 'grep -v "cannot be loaded as audit interface" "$tmp/stderr" >&3 || true; rm -rf "$tmp"' EXIT
failed=0

pass() { echo "PASS  $1"; }
fail() { echo "FAIL  $1${2:+: $2}"; failed=1; }

# --- build a fake archive layout ------------------------------------------------

mk_archive() {
    # mk_archive DIR [CUDA12]: create a fake archive installation in DIR.
    _d=$1
    mkdir -p "$_d/lib" "$_d/forward" "$_d/bin" "$_d/scripts"
    : >"$_d/lib/libcuda.so.1"
    : >"$_d/lib/libnvJitLink.so.13"
    : >"$_d/lib/libvf_audit.so"
    # (A stand-in for the offline tool, which says what it was given, one argument a line.)
    printf '#!/bin/sh\nprintf "%%s\\n" "$@"\n' >"$_d/bin/vf-translate"
    chmod +x "$_d/bin/vf-translate"
    : >"$_d/forward/libcublas.so.13"
    : >"$_d/forward/libcublasLt.so.13"
    : >"$_d/forward/libcufft.so.12"
    # A minimal REPORT.txt.
    cat >"$_d/forward/REPORT.txt" <<'REPORT'
Forwarding libraries generated by vf-fwdgen

library                      exports forwarded renumbered  adapted   absent  changed   serves
libcublas.so.13                  756       746         0        0       10        0   libcublas.so.12
libcublasLt.so.13                222       175         0       36       11        0   libcublasLt.so.12
libcufft.so.12                    75        57         0        1       17        0   libcufft.so.11
total                           9710      9492      6768       49      169        0
REPORT
    echo "0.1.0 test" > "$_d/VERSION"
    # Copy the launcher into bin/.
    cp "$launcher" "$_d/bin/vf"
    chmod +x "$_d/bin/vf"
    ln -s vf "$_d/bin/volta-forever"
    # The fetch script (a stub).
    cat >"$_d/scripts/fetch-redist.py" <<'PY'
#!/usr/bin/env python3
import sys
print("fetch-redist: " + " ".join(sys.argv[1:]))
PY
    chmod +x "$_d/scripts/fetch-redist.py"
    # CUDA 12.9.2 libraries, when asked: all of them, or cuBLAS alone (what `vf fetch`
    # downloads when it is not told --all).
    if [ "${2:-}" = "cuda12" ] || [ "${2:-}" = "cublas-only" ]; then
        mkdir -p "$_d/cuda-12.9.2/lib"
        : >"$_d/cuda-12.9.2/lib/libcublas.so.12"
        : >"$_d/cuda-12.9.2/lib/libcublasLt.so.12"
    fi
    if [ "${2:-}" = "cuda12" ]; then
        : >"$_d/cuda-12.9.2/lib/libcufft.so.11"
        : >"$_d/cuda-12.9.2/lib/libnvJitLink.so.12"
    fi
}

# --- build a fake source-tree layout --------------------------------------------

mk_source() {
    _d=$1
    mkdir -p "$_d/dist/lib" "$_d/dist/forward" "$_d/scripts"
    : >"$_d/dist/lib/libcuda.so.1"
    : >"$_d/dist/lib/libnvJitLink.so.13"
    : >"$_d/dist/lib/libvf_audit.so"
    : >"$_d/dist/forward/libcublas.so.13"
    : >"$_d/dist/forward/libcublasLt.so.13"
    cat >"$_d/dist/forward/REPORT.txt" <<'REPORT'
Forwarding libraries generated by vf-fwdgen

library                      exports forwarded renumbered  adapted   absent  changed   serves
libcublas.so.13                  756       746         0        0       10        0   libcublas.so.12
libcublasLt.so.13                222       175         0       36       11        0   libcublasLt.so.12
total                           9710      9492      6768       49      169        0
