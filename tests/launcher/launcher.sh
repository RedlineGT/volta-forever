: >"$tmp/my-cuda12/libcublas.so.12"
ldp=$(run_var "$vf" LD_LIBRARY_PATH --cuda12 "$tmp/my-cuda12")
case $ldp in
    *"$tmp/my-cuda12"*)
        pass "$name" ;;
    *)
        fail "$name" "custom cuda12 not in LD_LIBRARY_PATH: $ldp" ;;
esac

# 8. VF_CUDA12 environment variable.

name="cuda12-env"
ldp=$(VF_CUDA12="$tmp/my-cuda12" run_var "$vf" LD_LIBRARY_PATH)
case $ldp in
    *"$tmp/my-cuda12"*)
        pass "$name" ;;
    *)
        fail "$name" "VF_CUDA12 not honored: $ldp" ;;
esac

# Relative CUDA paths must keep pointing to the same files after the program changes directory.
name="cuda12-relative"
if (cd "$tmp" && "$vf" --cuda12 my-cuda12 sh -c '
    cd /
    case ":$LD_LIBRARY_PATH:" in *":$1/my-cuda12:"*) ;; *) exit 1 ;; esac
' sh "$tmp") && (cd "$tmp" && VF_CUDA12=my-cuda12 "$vf" sh -c '
    cd /
    case ":$VF_AUDIT_MAP:" in *":libcublas.so.12=$1/my-cuda12/libcublas.so.12:"*) ;; *) exit 1 ;; esac
' sh "$tmp"); then
    pass "$name"
else
    fail "$name" "relative CUDA library directory lost when the command changes directory"
fi

# 9. Warning when CUDA 12.9.2 is absent.

name="warn-no-cuda12"
arch_no_cuda=$tmp/archive-no-cuda
mk_archive "$arch_no_cuda"
vfnc=$arch_no_cuda/bin/vf
warn=$("$vfnc" env 2>&1 1>/dev/null) || true
case $warn in
    *"CUDA 12.9.2 libraries not found"*"vf fetch"*)
        pass "$name" ;;
    *)
        fail "$name" "warning not shown: $warn" ;;
esac

# 10. VF_QUIET=1 silences the warning.

name="quiet-no-warn"
warn=$(VF_QUIET=1 "$vfnc" env 2>&1 1>/dev/null) || true
if [ -z "$warn" ]; then
    pass "$name"
else
    fail "$name" "warning shown despite VF_QUIET=1: $warn"
fi

# 11. Arguments with spaces and empty arguments passed intact.

name="args-spaces"
out=$("$vf" sh -c 'printf "%s\n" "$@"' _ "hello world" "" "a  b")
expected="hello world

a  b"
if [ "$out" = "$expected" ]; then
    pass "$name"
else
    fail "$name" "got: $out"
fi

# 12. Exit status of the command is passed through.

name="exit-status"
"$vf" sh -c 'exit 42' 2>/dev/null || _status=$?
if [ "${_status:-0}" = 42 ]; then
    pass "$name"
else
    fail "$name" "expected 42, got: ${_status:-0}"
fi

# 13. env applied twice does not duplicate path entries.

name="env-no-dup"
# (The second `env` runs with the first one's variables. LD_AUDIT is left out of what is
# applied here: the audit library of this installation is an empty file, which the loader
# would complain of at every command.)
first=$("$vf" env)
ldp1=$(eval "$first"; printf '%s' "$LD_LIBRARY_PATH")
ldp2=$(eval "$first"; unset LD_AUDIT; eval "$("$vf" env)"; printf '%s' "$LD_LIBRARY_PATH")
if [ -n "$ldp1" ] && [ "$ldp1" = "$ldp2" ]; then
    pass "$name"
else
    fail "$name" "paths differ after second eval: $ldp1 / $ldp2"
fi

# 13b. What env prints is read back by eval as it is, whatever the path holds: a space, a
# dollar, a quote, a backquote.
name="env-quoting"
odd="$tmp/a b/it's \$HOME \`x\`"
mk_archive "$odd" cuda12
got=$(eval "$("$odd/bin/vf" env)"; printf '%s' "$VOLTA_FOREVER_HOME")
if [ "$got" = "$odd" ]; then
    pass "$name"
else
    fail "$name" "home read back as: $got"
fi

# 13c. The marker is the version alone, as the library gives it.
name="marker-version"
got=$(get_var "$vf" VOLTA_FOREVER)
if [ "$got" = "0.1.0" ]; then
    pass "$name"
else
    fail "$name" "VOLTA_FOREVER is: $got"
fi

# 14. Symlinked launcher.

name="symlink"
mkdir -p "$tmp/linked-bin"
ln -s "$vf" "$tmp/linked-bin/vf"
vfh=$("$tmp/linked-bin/vf" sh -c 'printf "%s" "$VOLTA_FOREVER_HOME"')
if [ "$vfh" = "$arch" ]; then
    pass "$name"
else
    fail "$name" "home through symlink: $vfh (expected $arch)"
fi

# 15. Source-tree layout.

name="source-layout"
src=$tmp/source
mk_source "$src"
vfs=$src/scripts/vf
ldp=$("$vfs" sh -c 'printf "%s" "$LD_LIBRARY_PATH"' 2>/dev/null)
case $ldp in
    "$src/dist/lib:$src/dist/forward"*)
        pass "$name" ;;
    *)
        fail "$name" "source layout LD_LIBRARY_PATH: $ldp" ;;
esac

name="source-version"
ver=$("$vfs" version)
case $ver in
    "0.1.0")
        pass "$name" ;;
    *)
        fail "$name" "version: $ver" ;;
esac

# 16. doctor exits non-zero when a required file is missing.

name="doctor-missing-file"
arch_doc=$tmp/archive-doctor
mk_archive "$arch_doc" cuda12
rm "$arch_doc/lib/libcuda.so.1"
"$arch_doc/bin/vf" doctor >"$tmp/doctor.out" 2>&1 || _dstat=$?
if [ "${_dstat:-0}" != 0 ]; then
    if grep -q "MISSING.*libcuda.so.1" "$tmp/doctor.out"; then
        pass "$name"
    else
        fail "$name" "did not mention libcuda.so.1"
