        pass "$name"
    else
        fail "$name" "status $_vstat, or a file was written"
    fi

    name="venv-refuses-a-directory-in-use"
    mkdir -p "$tmp/in-use"
    : >"$tmp/in-use/something"
    _vstat=0
    "$vfv" venv "$tmp/in-use" >/dev/null 2>&1 || _vstat=$?
    if [ "$_vstat" = 2 ] && [ ! -e "$tmp/in-use/pyvenv.cfg" ]; then
        pass "$name"
    else
        fail "$name" "status $_vstat, or the directory was made an environment"
    fi

    name="venv-off"
    "$vfv" venv --off "$ve" >/dev/null 2>&1 || true
    got=$("$ve/bin/python" -c 'import os; print(os.environ.get("VOLTA_FOREVER"))')
    if [ "$got" = None ] && [ -z "$(find "$ve" -name 'volta_forever*')" ]; then
        pass "$name"
    else
        fail "$name" "after --off: $got"
    fi

    # The launcher gone from where the environment has it: its Python starts as it is.
    name="venv-launcher-gone"
    "$vfv" venv "$ve" >/dev/null 2>&1 || true
    mv "$tmp/arch-venv" "$tmp/arch-gone"
    got=$("$ve/bin/python" -c 'import os; print(os.environ.get("VOLTA_FOREVER"))')
    if [ "$got" = None ]; then pass "$name"; else fail "$name" "with the launcher gone: $got"; fi
else
    echo "SKIP  venv (no python3 of 3.10 or later with the venv module)"
fi

