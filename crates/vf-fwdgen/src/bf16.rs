/// Structures passed by pointer or whose space the runtime provides: their sizes.
const STRUCTS: &[(&str, &str)] = &[
    ("CUmemPoolProps", "cuda.h"),
    ("CUmemLocation", "cuda.h"),
    ("cublasLtMatmulDescOpaque_t", "cublasLt.h"),
    ("cublasLtMatrixLayoutOpaque_t", "cublasLt.h"),
    ("cublasLtMatmulAlgo_t", "cublasLt.h"),
];

/// Macros: their values, read by a probe of the headers.
const MACROS: &[(&str, &str)] = &[("CU_STREAM_LEGACY", "cuda.h"), ("CU_STREAM_PER_THREAD", "cuda.h")];

fn is_driver(name: &str) -> bool {
    name.starts_with("cu") && !name.starts_with("cublas")
}

fn macro_values(include: &Path, header: &str, names: &[&str], work: &Path, tag: &str) -> Result<Vec<u64>, String> {
    std::fs::create_dir_all(work).map_err(|e| e.to_string())?;
    let probe = work.join(format!("{tag}.c"));
    let mut code = format!("#include <{header}>\n#include <stdio.h>\nint main(void) {{\n");
    for n in names {
        writeln!(code, "    printf(\"%llu\\n\", (unsigned long long)({n}));").unwrap();
    }
    code.push_str("    return 0;\n}\n");
    std::fs::write(&probe, code).map_err(|e| e.to_string())?;
    let exe = work.join(tag);
    let built = Command::new("gcc")
        .arg("-w")
        .arg(format!("-I{}", include.display()))
        .arg("-o")
        .arg(&exe)
        .arg(&probe)
        .output()
        .map_err(|e| format!("gcc: {e}"))?;
    if !built.status.success() {
        return Err(format!("probe of {header}: {}", String::from_utf8_lossy(&built.stderr)));
    }
    let run = Command::new(&exe).output().map_err(|e| e.to_string())?;
    String::from_utf8_lossy(&run.stdout)
        .lines()
        .map(|l| l.trim().parse::<u64>().map_err(|e| e.to_string()))
        .collect()
}

/// Every prototype, enumerator, structure size and macro of decls.h against the headers of CUDA 12.9
/// (all of them) and 13.5 (cuBLAS and cuBLASLt: what a program built against 13.5 passes to the
/// variants). Returns the problems found.
pub fn check_declarations(args: &Args, work: &Path) -> Result<Vec<String>, String> {
    let work = work.join("bf16-decls");
    std::fs::create_dir_all(&work).map_err(|e| e.to_string())?;
    let ours_dir = work.join("ours");
    std::fs::create_dir_all(&ours_dir).map_err(|e| e.to_string())?;
    std::fs::write(ours_dir.join("decls.h"), RT_DECLS).map_err(|e| e.to_string())?;
    let ours = protos::read_group(&ours_dir, &["decls.h"], &[], &work, "ours")?;
    let mut problems = Vec::new();
    for (lib_dir, version, all) in [(&args.old, "12.9", true), (&args.new, "13.5", false)] {
        let include = include_dir(lib_dir);
        let theirs = protos::read_group(
            &include,
            &["cuda.h", "cublas_v2.h", "cublasLt.h"],
            &[],
            &work,
            &format!("theirs-{version}"),
        )?;
        for (name, p) in &ours {
            if !all && is_driver(name) {
                continue;
            }
            match theirs.get(name) {
                None => problems.push(format!("{name}: not declared by the CUDA {version} headers")),
                Some(t) if t.ret != p.ret || t.params != p.params => problems.push(format!(
                    "{name}: decls.h has `{} ({})`, CUDA {version} `{} ({})`",
                    p.ret, p.params, t.ret, t.params
                )),
                _ => {}
            }
        }
        for (ty, header, complete) in ENUMS {
            if !all && *header == "cuda.h" {
                continue;
            }
            let tag = |who: &str| format!("enum-{who}-{version}-{ty}");
            let mine = protos::enum_values(&ours_dir, &["decls.h"], ty, &work, &tag("ours"))?;
            let theirs = protos::enum_values(&include, &[header], ty, &work, &tag("theirs"))?;
            let map: BTreeMap<&str, i64> = theirs.iter().map(|(n, v)| (n.as_str(), *v)).collect();
            for (n, v) in &mine {
                match map.get(n.as_str()) {
                    // The complete lists are 12.9's: a descriptor is made by 12.9 and holds only
                    // its attributes. Of 13.5's, only that a shared name has the same value matters.
                    None if *complete && version != "12.9" => {}
                    None => problems.push(format!("{ty}::{n}: not in the CUDA {version} headers")),
                    Some(w) if w != v => problems.push(format!("{ty}::{n} = {v} in decls.h, {w} in CUDA {version}")),
                    _ => {}
                }
            }
            if *complete && version == "12.9" {
                let mine: BTreeSet<&str> = mine.iter().map(|(n, _)| n.as_str()).collect();
                for (n, _) in &theirs {
                    if !mine.contains(n.as_str()) {
                        problems.push(format!("{ty}::{n} of CUDA {version} is missing from decls.h"));
                    }
                }
            }
        }
        if all {
            for (ty, header) in STRUCTS {
                let mine = protos::type_sizes(
                    &ours_dir,
                    &["decls.h"],
                    &[ty.to_string()],
                    &work,
                    &format!("sz-ours-{ty}"),
                )?;
                let theirs = protos::type_sizes(
                    &include,
                    &[header],
                    &[ty.to_string()],
                    &work,
                    &format!("sz-{version}-{ty}"),
                )?;
                if mine.get(*ty) != theirs.get(*ty) {
                    problems.push(format!(
                        "sizeof({ty}) is {:?} in decls.h, {:?} in CUDA {version}",
                        mine.get(*ty),
                        theirs.get(*ty)
                    ));
                }
            }
            for (name, header) in MACROS {
                let mine = macro_values(&ours_dir, "decls.h", &[name], &work, &format!("mac-ours-{name}"))?;
                let theirs = macro_values(&include, header, &[name], &work, &format!("mac-{version}-{name}"))?;
                if mine != theirs {
                    problems.push(format!("{name} is {mine:?} in decls.h, {theirs:?} in CUDA {version}"));
                }
            }
        }
    }
    Ok(problems)
}

