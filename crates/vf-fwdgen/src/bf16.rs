/// SHA-256 (FIPS 180-4), for the manifest of the kernels.
pub fn sha256(data: &[u8]) -> String {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5, 0xd807aa98,
        0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786,
        0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8,
        0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
        0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819,
        0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a,
        0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
    ];
    let mut msg = data.to_vec();
    let bits = (data.len() as u64).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&bits.to_be_bytes());
    for block in msg.chunks(64) {
        let mut w = [0u32; 64];
        for i in 0..16 {
            w[i] = u32::from_be_bytes(block[4 * i..4 * i + 4].try_into().unwrap());
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let mut v = h;
        for i in 0..64 {
            let s1 = v[4].rotate_right(6) ^ v[4].rotate_right(11) ^ v[4].rotate_right(25);
            let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
            let t1 = v[7]
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K[i])
                .wrapping_add(w[i]);
            let s0 = v[0].rotate_right(2) ^ v[0].rotate_right(13) ^ v[0].rotate_right(22);
            let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
            let t2 = s0.wrapping_add(maj);
            v = [
                t1.wrapping_add(t2),
                v[0],
                v[1],
                v[2],
                v[3].wrapping_add(t1),
                v[4],
                v[5],
                v[6],
            ];
        }
        for i in 0..8 {
            h[i] = h[i].wrapping_add(v[i]);
        }
    }
    h.iter().map(|x| format!("{x:08x}")).collect()
}

/// The hash the manifest records for one of its files.
pub fn manifest_hash(kind: &str, file: &str) -> Option<&'static str> {
    MANIFEST.lines().find_map(|l| {
        let f: Vec<&str> = l.split_whitespace().collect();
        (f.len() == 3 && f[0] == kind && f[1] == file).then_some(f[2])
    })
}

/// Problems of the kernels as compiled into this generator: the manifest's hashes, and what the fat
/// binary holds (sm_70 machine code only, one image, uncompressed).
pub fn check_kernels() -> Vec<String> {
    let mut problems = Vec::new();
    for (kind, file, bytes) in [
        ("source", "kernels.cu", RT_KERNELS.as_bytes()),
        ("source", "abi.h", RT_ABI.as_bytes()),
        ("fatbin", "kernels.fatbin", FATBIN),
    ] {
        match manifest_hash(kind, file) {
            None => problems.push(format!("kernels.manifest has no hash of {file}")),
            Some(h) if h != sha256(bytes) => problems.push(format!(
                "{file} is not what kernels.manifest records (scripts/build-bf16-kernels.sh rebuilds both)"
            )),
            _ => {}
        }
    }
    match vf_fatbin::parse(FATBIN) {
        Err(e) => problems.push(format!("kernels.fatbin is not a fat binary: {e:?}")),
        Ok(fat) => {
            let kinds: Vec<(u16, u32, bool)> = fat
                .entries
                .iter()
                .map(|e| (e.kind(), e.sm(), e.is_compressed()))
                .collect();
            if kinds != [(vf_fatbin::KIND_ELF, 70, false)] {
                problems.push(format!(
                    "kernels.fatbin holds {kinds:?} (kind, sm, compressed), not one uncompressed sm_70 image"
                ));
            }
        }
    }
    problems
}

/// Problems of the built runtime: its exports, its imports, and the kernels it embeds.
pub fn check_runtime(path: &Path) -> Vec<String> {
    let mut problems = Vec::new();
    let lib = match elf::read(path) {
        Ok(l) => l,
        Err(e) => return vec![e],
    };
    let want: BTreeSet<String> = std::iter::once("vf_bf16_init".to_string())
        .chain(
            VARIANTS
                .iter()
                .flat_map(|v| v.intercepts.iter().map(|n| runtime_symbol(n))),
        )
        .collect();
    let have: BTreeSet<String> = lib.exports.iter().map(|s| s.name.clone()).collect();
    if want != have {
        problems.push(format!(
            "exports {:?}, not {:?}",
            have.difference(&want).collect::<Vec<_>>(),
            want.difference(&have).collect::<Vec<_>>()
        ));
    }
    if lib.needed.iter().any(|n| {
        !(n.starts_with("libc.so")
            || n.starts_with("libdl.so")
            || n.starts_with("libpthread.so")
            || n.starts_with("ld-linux"))
    }) {
        problems.push(format!("needs {:?}", lib.needed));
    }
    for imp in lib.imports.iter().filter(|s| !s.weak) {
        let c = std::ffi::CString::new(imp.name.as_str()).unwrap();
        // SAFETY: dlsym with a valid handle constant and a NUL-terminated name.
        if unsafe { libc::dlsym(libc::RTLD_DEFAULT, c.as_ptr()) }.is_null() {
            problems.push(format!("undefined symbol {} is not from the C library", imp.name));
        }
    }
    match std::fs::read(path) {
        Ok(bytes) => {
            if !bytes.windows(FATBIN.len()).any(|w| w == FATBIN) {
                problems.push("the kernels of kernels.fatbin are not in it".into());
            }
        }
        Err(e) => problems.push(e.to_string()),
    }
    problems
}

/// Problems of a variant beyond those of any forwarding library: the intercepted exports jump to the
/// runtime's slots, the others as in the default library.
pub fn check_variant(spec: &LibSpec, gen_dir: &Path) -> Vec<String> {
    let Some(variant) = variant_of(spec.key) else {
        return vec![format!("{} has no variant", spec.new_name)];
    };
    let asm = match std::fs::read_to_string(gen_dir.join("fwd.S")) {
        Ok(a) => a,
        Err(e) => return vec![e.to_string()],
    };
    let mut problems = Vec::new();
    let jumps = asm.matches("jmp vf_icpt_slow").count();
    if jumps != variant.intercepts.len() {
        problems.push(format!(
            "{} functions jump to the runtime's slots, not {}",
            jumps,
            variant.intercepts.len()
        ));
    }
    for name in variant.intercepts {
        let start = asm.find(&format!("\n{name}:\n"));
        let body = start.map(|s| &asm[s..asm[s..].find(".size").map_or(asm.len(), |e| s + e)]);
        if !body.is_some_and(|b| b.contains("vf_icpt")) {
            problems.push(format!("{name} does not jump through the runtime's slot"));
        }
    }
    problems
}

