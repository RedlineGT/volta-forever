//! The bf16 variants of the cuBLAS forwarding libraries (`OUT/bf16tc/`), and their runtime.
//!
//! A variant has the exports, versions and SONAME of the default library and forwards every function
//! to CUDA 12.9 in the same way, except the few that the runtime (`libvf_cublas_bf16.so`, built here
//! from `bf16tc/runtime.c` and the checked-in fat binary of `bf16tc/kernels.cu`) defines as
//! `vf_bf16_<name>`: those jump through a slot of their own, bound at the first call to the
//! runtime's function when a switch is set and the runtime loads, else to the 12.9 function. The
//! default libraries are generated by the same code as before and are not touched by any of this.
//!
//! The runtime is built against `bf16tc/decls.h`, this project's declarations of what it uses of
//! the CUDA driver, cuBLAS and cuBLASLt; `check_declarations` compares them with the toolkits'
//! headers when the variants are generated.

use crate::libs::LibSpec;
use crate::plan::{Action, Entry, Return, StubReason};
use crate::{Args, elf, include_dir, protos};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The subdirectory of the forwarders' directory that holds the variants and the runtime.
pub const DIR: &str = "bf16tc";
pub const RUNTIME: &str = "libvf_cublas_bf16.so";

/// The exports of each library that the runtime serves.
pub struct Variant {
    pub key: &'static str,
    pub intercepts: &'static [&'static str],
}

pub const VARIANTS: &[Variant] = &[
    Variant {
        key: "cublas",
        intercepts: &[
            "cublasCreate_v2",
            "cublasDestroy_v2",
            "cublasGemmEx",
            "cublasGemmEx_64",
            "cublasGemmStridedBatchedEx",
            "cublasGemmStridedBatchedEx_64",
        ],
    },
    Variant {
        key: "cublasLt",
        intercepts: &["cublasLtCreate", "cublasLtDestroy", "cublasLtMatmul"],
    },
];

pub fn variant_of(key: &str) -> Option<&'static Variant> {
    VARIANTS.iter().find(|v| v.key == key)
}

/// The runtime's name for an intercepted function.
pub fn runtime_symbol(name: &str) -> String {
    format!("vf_bf16_{name}")
}

const RUNTIME_C: &str = include_str!("runtime.c");
const COMMON_ASM: &str = include_str!("common.S");
const VARIANT_C: &str = include_str!("bf16_variant.c");
const VARIANT_ASM: &str = include_str!("bf16_variant.S");
const RT_C: &str = include_str!("../bf16tc/runtime.c");
const RT_DECLS: &str = include_str!("../bf16tc/decls.h");
const RT_ABI: &str = include_str!("../bf16tc/abi.h");
const RT_ASM: &str = include_str!("../bf16tc/kernels.S");
const RT_KERNELS: &str = include_str!("../bf16tc/kernels.cu");
pub const FATBIN: &[u8] = include_bytes!("../bf16tc/kernels.fatbin");
pub const MANIFEST: &str = include_str!("../bf16tc/kernels.manifest");

fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The sources of a variant: the default library's, with the intercepted functions jumping through
/// slots of their own (`vf_icpt`), and the variant's part of the runtime (`bf16_variant.c`).
pub fn write_variant_sources(
    spec: &LibSpec,
    variant: &Variant,
    entries: &[Entry],
    target: &str,
    renumbering: &crate::emit::Renumbering,
    dir: &Path,
) -> Result<usize, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let mut slot_of: BTreeMap<&str, usize> = BTreeMap::new();
    let mut targets: Vec<(&str, Option<&str>)> = Vec::new();
    for e in entries {
        if let Action::Forward { target } | Action::ForwardStatus { target, .. } = &e.action {
            slot_of.insert(&e.name, targets.len());
            targets.push((target, e.note.as_deref()));
        }
    }
    let mut icpt_of: BTreeMap<&str, usize> = BTreeMap::new();
    for name in variant.intercepts {
        let e = entries
            .iter()
            .find(|e| e.name == *name)
            .ok_or(format!("{}: no export {name} to intercept", spec.new_name))?;
        if !matches!(&e.action, Action::Forward { target } if target == name) {
            return Err(format!(
                "{}: {name} is not a plain forward ({:?}); the runtime cannot take it",
                spec.new_name, e.action
            ));
        }
        icpt_of.insert(name, icpt_of.len());
    }

    let mut asm = String::new();
    asm.push_str("# Generated by vf-fwdgen (bf16 variant). One jump per forwarded function.\n.text\n.hidden vf_slots\n.hidden vf_icpt\n");
    asm.push_str(COMMON_ASM);
    asm.push_str(VARIANT_ASM);
    for e in entries {
        let Some(&i) = slot_of.get(e.name.as_str()) else {
            continue;
        };
        let n = &e.name;
        writeln!(
            asm,
            "    .globl {n}\n    .type {n},@function\n    .p2align 4\n{n}:\n    endbr64"
        )
        .unwrap();
        match (&e.action, icpt_of.get(n.as_str())) {
            (_, Some(&j)) => {
                writeln!(asm, "    mov vf_icpt+{}(%rip),%r11\n    test %r11,%r11\n    jz 1f\n    jmp *%r11\n1:  mov ${j},%r11d\n    jmp vf_icpt_slow", 8 * j).unwrap();
            }
            (Action::Forward { .. }, None) => {
                writeln!(asm, "    mov vf_slots+{}(%rip),%r11\n    test %r11,%r11\n    jz 1f\n    jmp *%r11\n1:  mov ${i},%r11d\n    jmp vf_fwd_slow", 8 * i).unwrap();
            }
            (Action::ForwardStatus { words, .. }, None) => {
                writeln!(
                    asm,
                    "    mov ${i},%r11d\n    mov ${words},%r10d\n    jmp vf_fwd_status_entry"
                )
                .unwrap();
            }
            _ => unreachable!(),
        }
        writeln!(asm, "    .size {n},.-{n}").unwrap();
    }
    asm.push_str(".section .note.GNU-stack,\"\",@progbits\n");
    std::fs::write(dir.join("fwd.S"), asm).map_err(|e| e.to_string())?;

    let mut c = String::new();
    c.push_str("// Generated by vf-fwdgen (bf16 variant).\n");
    writeln!(c, "#define VF_LIB {}", c_string(spec.new_name)).unwrap();
    writeln!(c, "#define VF_TARGET {}", c_string(target)).unwrap();
    writeln!(
        c,
        "#define VF_ENV {}",
        c_string(&format!("VF_FWD_{}", spec.key.to_uppercase().replace('-', "_")))
    )
    .unwrap();
    writeln!(c, "#define VF_NSLOTS {}", targets.len()).unwrap();
    writeln!(
        c,
        "#define VF_STATUS_TYPE {}",
        spec.status.as_ref().map_or("int", |s| s.ty)
    )
    .unwrap();
    if spec.status.is_some() {
        c.push_str("#define VF_HAS_STATUS 1\n");
    }
    writeln!(c, "#define VF_NICPT {}", icpt_of.len()).unwrap();
    writeln!(c, "#define VF_RUNTIME {}", c_string(RUNTIME)).unwrap();
    c.push_str(RUNTIME_C);
    c.push_str(VARIANT_C);
    c.push_str("\nconst char *const vf_targets[VF_NSLOTS + 1] = {\n");
    for (t, _) in &targets {
        writeln!(c, "    {},", c_string(t)).unwrap();
    }
    c.push_str("    0};\nconst char *const vf_notes[VF_NSLOTS + 1] = {\n");
    for (_, note) in &targets {
        match note {
            Some(n) => writeln!(c, "    {},", c_string(n)).unwrap(),
            None => c.push_str("    0,\n"),
        }
    }
    c.push_str("    0};\nconst char *const vf_icpt_names[VF_NICPT + 1] = {\n");
    for name in variant.intercepts {
        writeln!(c, "    {},", c_string(&runtime_symbol(name))).unwrap();
    }
    c.push_str("    0};\nconst unsigned vf_icpt_slots[VF_NICPT + 1] = {\n");
    for name in variant.intercepts {
        writeln!(c, "    {},", slot_of[name]).unwrap();
    }
    c.push_str("    0};\n");
    c.push_str("\nint vf_fwd_xlat(int status) {\n    switch (status) {\n");
    for (old, new) in renumbering {
        writeln!(c, "    case {old}: return {new};").unwrap();
    }
    c.push_str("    default: return status;\n    }\n}\n");
    c.push_str("\n// Functions the 12.9 library does not serve.\n");
    for e in entries {
        let Action::Stub { ret, reason } = &e.action else {
            continue;
        };
        let why = match reason {
            StubReason::Absent => "the CUDA 12.9 library has no such function".to_string(),
            StubReason::SignatureChanged(..) => {
                "its prototype changed between CUDA 12.9 and 13 and no adaptation is known".to_string()
            }
        };
        let (ty, value) = match (ret, spec.status.is_some()) {
            (Return::Status, _) | (Return::Unknown, true) => ("int", "vf_status_ns"),
            (Return::Unknown, false) | (Return::Int, _) => ("long", "0"),
            (Return::Pointer, _) => ("void *", "0"),
            (Return::Float, _) => ("float", "0"),
            (Return::Double, _) => ("double", "0"),
            (Return::Void, _) => ("void", ""),
        };
        let ret_stmt = if ty == "void" {
            String::new()
        } else {
            format!("return {value};")
        };
        writeln!(
            c,
            "EXPORT {ty} {}(void) {{ static char said; vf_unsupported(&said, {}, {}); {ret_stmt} }}",
            e.name,
            c_string(&e.name),
            c_string(&why)
        )
        .unwrap();
    }
    std::fs::write(dir.join("fwd.c"), c).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("ver.map"), crate::emit::version_script(spec, entries)).map_err(|e| e.to_string())?;
    let mut list = String::new();
    for name in variant.intercepts {
        writeln!(list, "{name}\t{}", runtime_symbol(name)).unwrap();
    }
    std::fs::write(dir.join("intercepts.tsv"), list).map_err(|e| e.to_string())?;
    Ok(icpt_of.len())
}

/// Builds the runtime into `out/bf16tc/libvf_cublas_bf16.so` from the sources compiled into this
/// generator. Imports from the C library only; the CUDA driver and libraries are opened at run time.
pub fn build_runtime(gen_root: &Path, out: &Path) -> Result<PathBuf, String> {
    let dir = gen_root.join("bf16tc-runtime");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    for (name, text) in [
        ("runtime.c", RT_C),
        ("decls.h", RT_DECLS),
        ("abi.h", RT_ABI),
        ("kernels.S", RT_ASM),
    ] {
        std::fs::write(dir.join(name), text).map_err(|e| e.to_string())?;
    }
    std::fs::write(dir.join("kernels.fatbin"), FATBIN).map_err(|e| e.to_string())?;
    let out_dir = out.join(DIR);
    std::fs::create_dir_all(&out_dir).map_err(|e| e.to_string())?;
    let target = out_dir.join(RUNTIME);
    let tmp = out_dir.join(format!(".{RUNTIME}.new"));
    let output = Command::new("gcc")
        .args(runtime_flags())
        .arg(format!("-ffile-prefix-map={}=.", dir.display()))
        .arg(format!("-Wa,-I{}", dir.display()))
        .arg("-o")
        .arg(&tmp)
        .arg(dir.join("runtime.c"))
        .arg(dir.join("kernels.S"))
        .arg(format!("-Wl,-soname,{RUNTIME}"))
        .args([
            "-Wl,--build-id=none",
            "-Wl,-z,relro,-z,now,-z,noexecstack,-z,defs",
            "-Wl,--as-needed",
            "-Wl,-s",
        ])
        .args(["-ldl", "-lpthread"])
        .output()
        .map_err(|e| format!("gcc: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "gcc for {RUNTIME}:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    std::fs::rename(&tmp, &target).map_err(|e| e.to_string())?;
    Ok(target)
}

/// The compiler flags of the runtime (also those of the host tests, tests/forward/bf16/).
pub fn runtime_flags() -> [&'static str; 11] {
    [
        "-shared",
        "-fPIC",
        "-O2",
        "-g0",
        "-std=gnu11",
        "-Wall",
        "-Wextra",
        "-Wno-unused-parameter",
        "-Werror",
        "-fvisibility=hidden",
        "-fno-ident",
    ]
}

