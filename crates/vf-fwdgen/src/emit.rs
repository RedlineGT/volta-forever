//! Writes the sources of one forwarding library (assembly jumps, C runtime, version script) and builds
//! it with gcc.

use crate::libs::LibSpec;
use crate::plan::{Action, Entry, Return, StubReason};
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The values of the status enumerators that changed: (12.9's value, 13.5's value).
pub type Renumbering = Vec<(i64, i64)>;

const RUNTIME: &str = include_str!("runtime.c");
const COMMON_ASM: &str = include_str!("common.S");

/// The file name `dlopen` is given for the 12.9 library. By SONAME, so that the loader's search
/// (LD_LIBRARY_PATH, the audit library's map) decides where it is; except when the 12.9 library has
/// the same SONAME as the one generated (cuSPARSE, cuRAND): the loader would hand back the forwarder
/// itself, so the real file's own name (`libcusparse.so.12.5.10.65`) is used.
pub fn target_name(spec: &LibSpec, old_dir: &Path) -> Result<String, String> {
    if spec.old_name != spec.new_name {
        return Ok(spec.old_name.to_string());
    }
    let real = std::fs::canonicalize(old_dir.join(spec.old_name)).map_err(|e| format!("{}: {e}", spec.old_name))?;
    let file = real
        .file_name()
        .and_then(|f| f.to_str())
        .ok_or("bad file name")?
        .to_string();
    if file == spec.old_name {
        return Err(format!(
            "{}: the 12.9 file has no name of its own besides its SONAME",
            spec.old_name
        ));
    }
    Ok(file)
}

fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// True when every export is bound to one version node that is named like the library's SONAME (what
/// all the NVIDIA libraries here have): the linker's `--default-symver` makes exactly that node, and
/// the script does not name it (a node name with a `-`, as in `libnvrtc-builtins.so.13.5`, is not
/// valid in a version script).
fn single_soname_node(spec: &LibSpec, entries: &[Entry]) -> bool {
    entries.iter().all(|e| e.version.as_deref() == Some(spec.new_name))
}

pub fn version_script(spec: &LibSpec, entries: &[Entry]) -> String {
    let mut nodes: BTreeMap<Option<&str>, Vec<&str>> = BTreeMap::new();
    let anonymous = single_soname_node(spec, entries);
    for e in entries {
        nodes
            .entry(if anonymous { None } else { e.version.as_deref() })
            .or_default()
            .push(&e.name);
    }
    let mut out = String::new();
    let count = nodes.len();
    for (i, (node, names)) in nodes.iter().enumerate() {
        match node {
            Some(n) => writeln!(out, "{n} {{").unwrap(),
            None => out.push_str("{\n"),
        }
        out.push_str("  global:\n");
        for name in names {
            writeln!(out, "    {name};").unwrap();
        }
        if i + 1 == count {
            out.push_str("  local: *;\n");
        }
        out.push_str("};\n");
    }
    let _ = spec;
    out
}

pub fn write_sources(
    spec: &LibSpec,
    entries: &[Entry],
    target: &str,
    renumbering: &Renumbering,
    dir: &Path,
) -> Result<usize, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    // Slots: one per function that jumps to the 12.9 library.
    let mut slot_of: BTreeMap<&str, usize> = BTreeMap::new();
    let mut targets: Vec<(&str, Option<&str>)> = Vec::new(); // (target name, note)
    for e in entries {
        if let Action::Forward { target } | Action::ForwardStatus { target, .. } = &e.action {
            slot_of.insert(&e.name, targets.len());
            targets.push((target, e.note.as_deref()));
        }
    }

    let mut asm = String::new();
    asm.push_str("# Generated by vf-fwdgen. One jump per forwarded function.\n.text\n.hidden vf_slots\n");
    asm.push_str(COMMON_ASM);
    for e in entries {
        let Some(&i) = slot_of.get(e.name.as_str()) else {
            continue;
        };
        let n = &e.name;
        writeln!(
            asm,
            "    .globl {n}\n    .type {n},@function\n    .p2align 4\n{n}:\n    endbr64"
        )
        .unwrap();
        match &e.action {
            Action::Forward { .. } => {
                writeln!(asm, "    mov vf_slots+{}(%rip),%r11\n    test %r11,%r11\n    jz 1f\n    jmp *%r11\n1:  mov ${i},%r11d\n    jmp vf_fwd_slow", 8 * i).unwrap();
            }
            Action::ForwardStatus { words, .. } => {
                writeln!(
                    asm,
                    "    mov ${i},%r11d\n    mov ${words},%r10d\n    jmp vf_fwd_status_entry"
                )
                .unwrap();
            }
            _ => unreachable!(),
        }
        writeln!(asm, "    .size {n},.-{n}").unwrap();
    }
    asm.push_str(".section .note.GNU-stack,\"\",@progbits\n");
    std::fs::write(dir.join("fwd.S"), asm).map_err(|e| e.to_string())?;

    let mut c = String::new();
    c.push_str("// Generated by vf-fwdgen.\n");
    writeln!(c, "#define VF_LIB {}", c_string(spec.new_name)).unwrap();
    writeln!(c, "#define VF_TARGET {}", c_string(target)).unwrap();
    writeln!(
        c,
        "#define VF_ENV {}",
        c_string(&format!("VF_FWD_{}", spec.key.to_uppercase().replace('-', "_")))
    )
    .unwrap();
    writeln!(c, "#define VF_NSLOTS {}", targets.len()).unwrap();
    writeln!(
        c,
        "#define VF_STATUS_TYPE {}",
        spec.status.as_ref().map_or("int", |s| s.ty)
    )
    .unwrap();
    if spec.status.is_some() {
        c.push_str("#define VF_HAS_STATUS 1\n");
    }
    c.push_str(RUNTIME);
    c.push_str("\nconst char *const vf_targets[VF_NSLOTS + 1] = {\n");
    for (t, _) in &targets {
        writeln!(c, "    {},", c_string(t)).unwrap();
    }
    c.push_str("    0};\nconst char *const vf_notes[VF_NSLOTS + 1] = {\n");
    for (_, note) in &targets {
        match note {
            Some(n) => writeln!(c, "    {},", c_string(n)).unwrap(),
            None => c.push_str("    0,\n"),
        }
    }
    c.push_str("    0};\n");

    // 12.9's status values to 13.5's (the identity when nothing was renumbered).
    c.push_str("\nint vf_fwd_xlat(int status) {\n    switch (status) {\n");
    for (old, new) in renumbering {
        writeln!(c, "    case {old}: return {new};").unwrap();
    }
    c.push_str("    default: return status;\n    }\n}\n");

    c.push_str("\n// Functions the 12.9 library does not serve.\n");
    for e in entries {
        let Action::Stub { ret, reason } = &e.action else {
            continue;
        };
        let why = match reason {
            StubReason::Absent => "the CUDA 12.9 library has no such function".to_string(),
            StubReason::SignatureChanged(..) => {
                "its prototype changed between CUDA 12.9 and 13 and no adaptation is known".to_string()
            }
        };
        let n = &e.name;
        let (ty, value) = match (ret, spec.status.is_some()) {
            (Return::Status, _) | (Return::Unknown, true) => ("int", "vf_status_ns"),
            (Return::Unknown, false) | (Return::Int, _) => ("long", "0"),
            (Return::Pointer, _) => ("void *", "0"),
            (Return::Float, _) => ("float", "0"),
            (Return::Double, _) => ("double", "0"),
            (Return::Void, _) => ("void", ""),
        };
        let ret_stmt = if ty == "void" {
            String::new()
        } else {
            format!("return {value};")
        };
        writeln!(
            c,
            "EXPORT {ty} {n}(void) {{ static char said; vf_unsupported(&said, {}, {}); {ret_stmt} }}",
            c_string(n),
            c_string(&why)
        )
        .unwrap();
    }
    std::fs::write(dir.join("fwd.c"), c).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("ver.map"), version_script(spec, entries)).map_err(|e| e.to_string())?;
    Ok(targets.len())
}

/// The file that gives the stubs the library's "not supported" value, compiled against the 13.5 headers.
pub fn write_status_source(spec: &LibSpec, dir: &Path) -> Result<(), String> {
    let mut s = String::new();
    if let Some(status) = &spec.status {
        for h in spec.headers[0] {
            writeln!(s, "#include <{h}>").unwrap();
        }
        writeln!(
            s,
            "__attribute__((visibility(\"hidden\"))) const int vf_status_ns = {};",
            status.not_supported
        )
        .unwrap();
    } else {
        s.push_str("typedef int vf_empty;\n");
    }
    std::fs::write(dir.join("status.c"), s).map_err(|e| e.to_string())
}

pub fn build(spec: &LibSpec, entries: &[Entry], dir: &Path, new_include: &Path, out: &Path) -> Result<PathBuf, String> {
    std::fs::create_dir_all(out).map_err(|e| e.to_string())?;
    let target = out.join(spec.new_name);
    let tmp = out.join(format!(".{}.new", spec.new_name));
    let output = Command::new("gcc")
        .args([
            "-shared",
            "-fPIC",
            "-O2",
            "-g0",
            "-Wall",
            "-Wextra",
            "-Wno-unused-parameter",
            "-fvisibility=hidden",
            "-fno-ident",
        ])
        .arg(format!("-ffile-prefix-map={}=.", dir.display()))
        .arg(format!("-I{}", new_include.display()))
        .arg("-o")
        .arg(&tmp)
        .arg(dir.join("fwd.S"))
        .arg(dir.join("fwd.c"))
        .arg(dir.join("status.c"))
        .arg(format!("-Wl,-soname,{}", spec.new_name))
        .arg(format!("-Wl,--version-script={}", dir.join("ver.map").display()))
        .args(single_soname_node(spec, entries).then_some("-Wl,--default-symver"))
        .args([
            "-Wl,--build-id=none",
            "-Wl,-z,relro,-z,now,-z,noexecstack",
            "-Wl,--as-needed",
            "-Wl,-s",
            "-ldl",
        ])
        .output()
        .map_err(|e| format!("gcc: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "gcc for {}:\n{}",
            spec.new_name,
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    std::fs::rename(&tmp, &target).map_err(|e| e.to_string())?;
    Ok(target)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::libs::LIBS;

    fn entry(name: &str, version: Option<&str>) -> Entry {
        Entry {
            name: name.into(),
            version: version.map(str::to_string),
            action: Action::Forward { target: name.into() },
            adapted: None,
            note: None,
        }
    }

    #[test]
    fn version_script_of_a_soname_node_is_anonymous() {
        let spec = LIBS.iter().find(|l| l.key == "cublas").unwrap();
        let entries = [entry("a", Some("libcublas.so.13")), entry("b", Some("libcublas.so.13"))];
        let script = version_script(spec, &entries);
        assert_eq!(script, "{\n  global:\n    a;\n    b;\n  local: *;\n};\n");
        assert!(single_soname_node(spec, &entries));
    }

    #[test]
    fn version_script_keeps_other_nodes() {
        let spec = LIBS.iter().find(|l| l.key == "cublas").unwrap();
        let entries = [entry("a", Some("V1")), entry("b", Some("V2"))];
        let script = version_script(spec, &entries);
        assert!(
            script.contains("V1 {\n  global:\n    a;\n};")
                && script.contains("V2 {")
                && script.ends_with("local: *;\n};\n")
        );
        assert!(!single_soname_node(spec, &entries));
    }

    #[test]
    fn c_strings_are_escaped() {
        assert_eq!(c_string("a\"b\\c"), "\"a\\\"b\\\\c\"");
    }
}
