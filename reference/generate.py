# ---- Rust code helpers ---------------------------------------------------------------------------------

def rust_str(s):
    """Return a valid Rust &str literal for the Python string `s`."""
    escaped = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    return '"%s"' % escaped


def emit_u128(v):
    lo = v & ((1 << 64) - 1)
    hi = (v >> 64) & ((1 << 64) - 1)
    return '0x%016x_%016x_u128' % (hi, lo)


