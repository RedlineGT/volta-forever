def emit_special(f, mc, fc, onc, classes_75, classes_70):
    """Write gen/special.rs with special data needed by the translator."""
    lines = [HEADER, '']

    type_code_map = {
        'Register': 1, 'NonZeroRegister': 1, 'ZeroRegister': 1,
        'RegisterFAU': 1, 'NonZeroRegisterFAU': 1, 'ZeroRegisterFAU': 1,
        'UniformRegister': 2, 'NonZeroUniformRegister': 2, 'ZeroUniformRegister': 2,
        'Predicate': 3, 'UniformPredicate': 4,
        'RSImm': 5,
    }

    # sm_75 operand types
    all_optypes = []
    optype_offsets = []
    for cl in classes_75:
        offset = len(all_optypes)
        for name, tp in cl['op_types'].items():
            nid = onc.add(name)
            tc = type_code_map.get(tp, 0)
            if tc > 0:
                all_optypes.append((nid, tc))
        optype_offsets.append((offset, len(all_optypes) - offset))

    lines.append('/// Operand type info for each sm_75 class: list of (op_name_id, type_code).')
    lines.append('/// type_code: 0=other, 1=Register, 2=UniformRegister, 3=Predicate, 4=UniformPredicate, 5=RSImm.')
    lines.append('pub static SM75_OP_TYPES: [(u16, u8); %d] = [' % len(all_optypes))
    for nid, tc in all_optypes:
        lines.append('    (%d, %d),' % (nid, tc))
    lines.append('];')
    lines.append('')

    lines.append('pub static SM75_OP_TYPE_OFFSETS: [(u32, u16); %d] = [' % len(optype_offsets))
    for off, length in optype_offsets:
        lines.append('    (%d, %d),' % (off, length))
    lines.append('];')
    lines.append('')

    # sm_70 operand types
    all_optypes70 = []
    optype_offsets70 = []
    for cl in classes_70:
        offset = len(all_optypes70)
        for name, tp in cl['op_types'].items():
            nid = onc.add(name)
            tc = type_code_map.get(tp, 0)
            if tc > 0:
                all_optypes70.append((nid, tc))
        optype_offsets70.append((offset, len(all_optypes70) - offset))

    lines.append('pub static VF_OP_TYPES: [(u16, u8); %d] = [' % len(all_optypes70))
    for nid, tc in all_optypes70:
        lines.append('    (%d, %d),' % (nid, tc))
    lines.append('];')
    lines.append('')

    lines.append('pub static VF_OP_TYPE_OFFSETS: [(u32, u16); %d] = [' % len(optype_offsets70))
    for off, length in optype_offsets70:
        lines.append('    (%d, %d),' % (off, length))
    lines.append('];')
    lines.append('')

    lines.append('pub const NOP: u128 = %s;' % emit_u128(MC.NOP))
    lines.append('pub const USCHED: u32 = %d;' % MC.USCHED)
    lines.append('pub const WRITE_BARRIER: u32 = %d;' % MC.WRITE_BARRIER)
    lines.append('pub const READ_BARRIER: u32 = %d;' % MC.READ_BARRIER)
    lines.append('pub const WAIT: u32 = %d;' % MC.WAIT)
    lines.append('pub const REUSE: u128 = %s;' % emit_u128(MC.REUSE))
    lines.append('')

    lines.append('pub const SCHEDULING: u128 = %s;' % emit_u128(remap.SCHEDULING))
    lines.append('')
    lines.append('/// Memory instructions of sm_75 whose address has a uniform part, by the start of the name of')
    lines.append('/// their class, and the sm_70 class of the plain instruction.')
    lines.append('pub const UNIFORM_ADDRESS: &[(&str, &str)] = &[%s];' % ', '.join('(%s, %s)' % (rust_str(a), rust_str(b)) for a, b in MC.UNIFORM_ADDRESS.items()))
    lines.append('/// Of those plain classes, the ones in shared memory: an address of 32 bits, whose register may')
    lines.append('/// have a stride.')
    lines.append('pub const SHARED: &[&str] = &[%s];' % ', '.join(rust_str(n) for n in MC.SHARED))
    lines.append('/// The classes whose address register may have a stride on sm_75 and has none on sm_70.')
    lines.append('pub const STRIDED: &[&str] = &[%s];' % ', '.join(rust_str(n) for n in MC.STRIDED))
    lines.append('')

    lines.append('pub const ZERO_R: u32 = 255;')
    lines.append('pub const ZERO_U: u32 = 63;')
    lines.append('pub const ZERO_P: u32 = 7;')
    lines.append('pub const ZERO_Q: u32 = 7;')
    lines.append('')

    f.write('\n'.join(lines))


