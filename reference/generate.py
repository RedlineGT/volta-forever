def check(mc):
    """What the translator takes for granted of the descriptions, so that it need not look it up."""
    for md, dec in ((mc.md75, mc.d75), (mc.md70, mc.d70)):
        for c in md.classes:
            # A distance in the code is one operand, held in one field with a scale.
            names = [n for n, o in c.operands.items() if o.type == 'RSImm']
            assert len(names) <= 1, c.name
            assert not names or any(k == 'scaled' and d[0] == names[0] for k, f, d in dec.plan(c)), c.name
        # A branch through a register: its number is in one scaled field (see `relative`).
        assert any(k == 'scaled' and d[0] == 'Ra_offset' for k, f, d in dec.plan(md.by_name['brx_']))
    for c in mc.md75.classes:
        if c.name.startswith('imnmx__'):
            assert dict(mc.md75.enums[c.operands['fmt'].type]) == {'U32': 0, 'S32': 1}, c.name
    sizes = {n.strip('_'): v for n, v in mc.md75.enums[mc.md75.by_name['uldc_const__RCR'].operands['sz'].type].items() if not n.startswith('INVALID')}
    assert sizes == {'U8': 0, 'S8': 1, 'U16': 2, 'S16': 3, '32': 4, '64': 5}, sizes
    assert mc.md70.enums[mc.md70.by_name['isetp__RRR_RR'].operands['fmt'].type]['S32'] == 1
    # The classes with a stride that sm_70 does not have, and the plain classes of memory instructions.
    strided = {n for n, c in mc.md75.by_name.items() if 'stride' in c.operands and n in mc.md70.by_name and 'stride' not in mc.md70.by_name[n].operands}
    assert strided == set(MC.STRIDED), strided ^ set(MC.STRIDED)
    assert all(plain in mc.md70.by_name for plain in MC.UNIFORM_ADDRESS.values())
    assert not any(a != b and a.startswith(b) for a in MC.UNIFORM_ADDRESS for b in MC.UNIFORM_ADDRESS)


def main():
    print('Loading descriptions and rules...')
    mc = MC.Machine()
    check(mc)

    fc = FieldCollector()
    onc = OpNameCollector()

    print('Analyzing sm_75 classes (%d)...' % len(mc.md75.classes))
    classes_75 = [analyze_class(mc.md75, mc.d75, mc.sets75, c, fc, onc) for c in mc.md75.classes]

    print('Analyzing sm_70 classes (%d)...' % len(mc.md70.classes))
    classes_70 = [analyze_class(mc.md70, mc.d70, mc.sets70, c, fc, onc) for c in mc.md70.classes]

    print('Fields: %d unique, operand names: %d' % (len(fc.fields), len(onc.names)))

    os.makedirs(OUT, exist_ok=True)

    import ampere_forms
    ampere_forms.write(os.path.join(OUT, 'ampere.rs'), HEADER)

    print('Writing lib.rs...')
    with open(os.path.join(OUT, 'lib.rs'), 'w') as f:
        emit_mod(f)

    print('Writing fields.rs (%d fields, %d operand names)...' % (len(fc.fields), len(onc.names)))
    with open(os.path.join(OUT, 'fields.rs'), 'w') as f:
        emit_field_data(f, fc, onc)

    print('Writing classes.rs...')
    with open(os.path.join(OUT, 'classes.rs'), 'w') as f:
        emit_classes(f, classes_75, classes_70, fc, onc)

    print('Writing rules.rs...')
    with open(os.path.join(OUT, 'rules.rs'), 'w') as f:
        emit_rules(f, mc, fc, onc, classes_75)

    print('Writing assembly.rs...')
    with open(os.path.join(OUT, 'assembly.rs'), 'w') as f:
        emit_assembly(f, mc, fc, onc)

    print('Writing distances.rs...')
    with open(os.path.join(OUT, 'distances.rs'), 'w') as f:
        emit_distances(f, mc)

    print('Writing special.rs...')
    with open(os.path.join(OUT, 'special.rs'), 'w') as f:
        emit_special(f, mc, fc, onc, classes_75, classes_70)

    print('Done. Generated files in %s' % OUT)


if __name__ == '__main__':
    main()
