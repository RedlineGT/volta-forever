#!/usr/bin/env python3
"""Generate Rust tables from NVIDIA's instruction descriptions for the sm_75 -> sm_70 translator.

Usage: cd REPO_ROOT && python3 -I reference/generate.py && cargo fmt -p vf-tables

Writes the files of crates/vf-tables/src/. They are committed (formatted: hence the second
command); regenerate them when the descriptions, the rules or the distances change.

The generator reads the same descriptions (md.py), rules (remap.py, rules-sm75.tsv) and distances
(distances-sm70.tsv) as the Python prototype, and emits Rust source code with all the data the
translator needs at run time: the fields of the two instruction sets, the classes (what an instruction
reads and writes, its kind for scheduling), the decoder tables, the rules for uniform operands, the
assembly templates for instructions the translator builds from scratch, and the distance table.
"""
