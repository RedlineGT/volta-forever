# ---- Field collection ----------------------------------------------------------------------------------

class FieldCollector:
    """Collects unique field definitions (by bit pattern) and assigns each an ID."""

    def __init__(self):
        self.by_bits = {}     # tuple(bits) -> field_id
        self.fields = []      # [(bits_tuple, mask)]

    def add(self, field):
        key = tuple(field.bits)
        if key in self.by_bits:
            fid = self.by_bits[key]
        else:
            fid = len(self.fields)
            self.by_bits[key] = fid
            self.fields.append((key, field.mask))
        return fid

    def add_by_name(self, md, name):
        return self.add(md.fields[name])


# ---- Operand name collection --------------------------------------------------------------------------

class OpNameCollector:
    """Collects unique operand name strings and assigns each an ID."""

    def __init__(self):
        self.by_name = {}
        self.names = []

    def add(self, name):
        if name not in self.by_name:
            self.by_name[name] = len(self.names)
            self.names.append(name)
        return self.by_name[name]


# ---- Class analysis ------------------------------------------------------------------------------------

KIND_MAP = {
    'FXU': 0, 'IMAD': 1, 'FMAI': 2, 'FMALITE': 3, 'FMA64HEAVY': 4,
    'MIO_FAST': 5, 'MIO_SLOW': 6, 'BRU': 7, 'HMMA': 8, 'IMMA': 9,
    'UDP': 10, 'OTHER': 11,
}

KIND_NAMES = ['FXU', 'IMAD', 'FMAI', 'FMALITE', 'FMA64HEAVY', 'MIO_FAST', 'MIO_SLOW', 'BRU', 'HMMA', 'IMMA', 'UDP', 'OTHER']


class SpanCollector:
    """The numbers of registers that depend on the instruction (latency.Size), as tables: one for
    every different way, indexed by the values of the operands the size is worked out from."""

    def __init__(self):
        self.tables, self.index = [], {}        # (keys [(operand name id, bits)], values)

    def code(self, md, dec, c, span, onc):
        """What stands for `span` in the tables of a class: the number itself, or 0x8000 + a table."""
        if isinstance(span, int):
            assert 0 < span < 0x8000
            return span
        width = {data: len(fields[0]) for kind, fields, data in dec.plan(c) if kind == 'operand'}
        names = span.names
        assert all(n in width for n in names), (c.name, span.text)
        assert sum(width[n] for n in names) <= 12, (c.name, span.text)
        values = []
        for combination in itertools.product(*[range(1 << width[n]) for n in names]):
            values.append(registers(span, dict(zip(names, combination))))
        key = (tuple((onc.add(n), width[n]) for n in names), tuple(values))
        if key not in self.index:
            self.index[key] = len(self.tables)
            self.tables.append(key)
        return 0x8000 + self.index[key]


SPANS = SpanCollector()


def analyze_class(md, dec, sets, c, fc, onc):
    """Analyze one class and return its data for the Rust tables."""
    plan = dec.plan(c)
    kind_str = kind_of(sets, c.mnemonic)
    kind_id = KIND_MAP[kind_str]

    # Opcode field and value
    opcode_fid = fc.add_by_name(md, c.opcode_field)
    opcode_value = c.opcode

    # Match conditions: constant checks and domain checks
    const_checks = []     # (field_id, expected_value)
    domain_checks = []    # (field_id, sorted list of valid values)
    for step_kind, fields, data in plan:
        if step_kind in ('const', 'default'):
            fid = fc.add(fields[0])
            const_checks.append((fid, data))
        elif step_kind == 'operand':
            o = c.operands.get(data)
            if o is not None:
                values = md.enums.get(o.type)
                if values is not None:
                    valid = sorted(v for s, v in values.items() if not s.startswith('INVALID'))
                    if valid:
                        fid = fc.add(fields[0])
                        domain_checks.append((fid, valid))
        elif step_kind == 'table':
            table = md.tables.get(data[0], [])
            valid = sorted(int(value, 0) for keys, value in table if re.fullmatch(r'-?\d+|0x[0-9a-fA-F]+', value))
            if valid:
                fid = fc.add(fields[0])
                domain_checks.append((fid, valid))

    # Unused mask (for sm_70 decode: bits not used by this class must be zero)
    unused_mask = 0
    for step_kind, fields, data in plan:
        if step_kind == 'unused':
            for f in fields:
                unused_mask |= f.mask

    # Operand entries: (name_id, field_id, scale, op_kind)
    # op_kind: 0=plain, 1=attribute, 2=scaled, 3=function, 4=table
    operand_entries = []
    for step_kind, fields, data in plan:
        if step_kind == 'operand':
            nid = onc.add(data)
            fid = fc.add(fields[0])
            operand_entries.append((nid, fid, 0, 0))
        elif step_kind == 'attribute':
            name = '%s@%s' % data
            nid = onc.add(name)
            fid = fc.add(fields[0])
            operand_entries.append((nid, fid, 0, 1))
        elif step_kind == 'scaled':
            nid = onc.add(data[0])
            fid = fc.add(fields[0])
            operand_entries.append((nid, fid, data[1], 2))
        elif step_kind == 'table':
            name = '%s(%s)' % (data[0], ','.join(data[1]))
            nid = onc.add(name)
            fid = fc.add(fields[0])
            operand_entries.append((nid, fid, 0, 4))
        elif step_kind == 'function':
            for f, a in zip(fields, data[1]):
                nid = onc.add(a)
                fid = fc.add(f)
                operand_entries.append((nid, fid, 0, 3))

    # Uses: reads and writes
    uses = Uses(md, c)
    reads = [(letter, onc.add(name), SPANS.code(md, dec, c, span, onc)) for letter, name, span in uses.reads]
    writes = [(letter, onc.add(name), SPANS.code(md, dec, c, span, onc)) for letter, name, span in uses.writes]

    # Operand type info
    op_types = {name: o.type for name, o in c.operands.items()}

    return {
        'name': c.name,
        'mnemonic': c.mnemonic,
        'alternate': c.alternate,
        'kind_id': kind_id,
        'kind_str': kind_str,
        'opcode_fid': opcode_fid,
        'opcode_value': opcode_value,
        'const_checks': const_checks,
        'domain_checks': domain_checks,
        'unused_mask': unused_mask,
        'operand_entries': operand_entries,
        'reads': reads,
        'writes': writes,
        'op_types': op_types,
    }


# ---- Rule analysis ------------------------------------------------------------------------------------

def analyze_rule(mc, fc, onc, sm75_name, sm70_name, drop=()):
    """Pre-compute a Rule for the Rust tables."""
    md75, d75 = mc.md75, mc.d75
    md70, d70 = mc.md70, mc.d70
    if sm75_name not in md75.by_name or sm70_name not in md70.by_name:
        return None
    a = md75.by_name[sm75_name]
    b = md70.by_name[sm70_name]
    rule = remap.Rule(md75, d75, a, md70, d70, b, drop)
    if not rule.ok:
        return None

    moves = []
    for src_fields, dst_fields, conv in rule.moves:
        src_fids = [fc.add(f) for f in src_fields]
        dst_fids = [fc.add(f) for f in dst_fields]
        conv_id = {'raw': 0, 'register': 1, 'predicate': 2, 'signed': 3}[conv]
        moves.append((src_fids, dst_fids, conv_id))

    allowed = []
    for field, valid_set in rule.allowed:
        fid = fc.add(field)
        allowed.append((fid, sorted(valid_set)))

    dropped = {}
    for key, fields in rule.dropped.items():
        dropped[key] = [fc.add(f) for f in fields]

    return {
        'sm75_name': sm75_name,
        'sm70_name': sm70_name,
        'moves': moves,
        'fixed': rule.fixed,
        'allowed': allowed,
        'dropped': dropped,
        'drop_tuple': drop,
    }


# ---- Assembly analysis ---------------------------------------------------------------------------------

def analyze_assembly(mc, fc, onc, class_name):
    """Pre-compute assembly data for an sm_70 class."""
    md70, d70 = mc.md70, mc.d70
    if class_name not in md70.by_name:
        return None
    c = md70.by_name[class_name]
    plan = d70.plan(c)

    base_word = 0
    setters = []
    attr_setters = []
    has_opex = False

    for step_kind, fields, data in plan:
        if step_kind in ('opcode', 'const', 'default'):
            base_word = fields[0].put(base_word, data)
        elif step_kind == 'operand':
            nid = onc.add(data)
            fid = fc.add(fields[0])
            default = remap.default_raw(md70, c, data)
            o = c.operands.get(data)
            enum_values = {}
            if o is not None:
                vals = md70.enums.get(o.type)
                if vals is not None:
                    enum_values = {s: v for s, v in vals.items() if not s.startswith('INVALID')}
            setters.append((nid, fid, 0, enum_values, default, data))
        elif step_kind == 'attribute':
            key = '%s_%s' % data
            fid = fc.add(fields[0])
            attr_setters.append((key, fid))
        elif step_kind == 'scaled':
            nid = onc.add(data[0])
            fid = fc.add(fields[0])
            default = remap.default_raw(md70, c, data[0])
            o = c.operands.get(data[0])
            enum_values = {}
            if o is not None:
                vals = md70.enums.get(o.type)
                if vals is not None:
                    enum_values = {s: v for s, v in vals.items() if not s.startswith('INVALID')}
            setters.append((nid, fid, data[1], enum_values, default, data[0]))
        elif step_kind == 'function':
            for f, a in zip(fields, data[1]):
                nid = onc.add(a)
                fid = fc.add(f)
                default = remap.default_raw(md70, c, a)
                o = c.operands.get(a)
                enum_values = {}
                if o is not None:
                    vals = md70.enums.get(o.type)
                    if vals is not None:
                        enum_values = {s: v for s, v in vals.items() if not s.startswith('INVALID')}
                setters.append((nid, fid, 0, enum_values, default, a))
        elif step_kind == 'table' and fields[0].name == 'BITS_8_124_122_109_105_opex':
            has_opex = True

    if has_opex:
        base_word |= 1 << MC.USCHED

    return {
        'name': class_name,
        'base_word': base_word,
        'setters': setters,
        'attr_setters': attr_setters,
    }


# ---- Emit Rust code ------------------------------------------------------------------------------------

def emit_field_data(f, fc, onc):
    """Write gen/fields.rs with field definitions."""
    lines = [HEADER, '']
    all_bits = []
    field_defs = []
    for bits, mask in fc.fields:
        offset = len(all_bits)
        length = len(bits)
        all_bits.extend(bits)
        if length > 0:
            sorted_bits = sorted(bits)
            is_contig = (sorted_bits[-1] - sorted_bits[0] + 1 == length) and bits == tuple(range(bits[0], bits[0] - length, -1))
            start = sorted_bits[0] if is_contig else 255
        else:
            is_contig = True
            start = 0
        field_defs.append((offset, length, mask, is_contig, start))

    lines.append('/// Bit positions of all fields, packed into a single array.')
    lines.append('/// Each field is a contiguous slice: FIELD_BITS[offset..offset+len].')
    lines.append('/// Bits are in most-significant-first order (the order Field.get iterates).')
    lines.append('pub static FIELD_BITS: [u8; %d] = [' % len(all_bits))
    for i in range(0, len(all_bits), 32):
        chunk = all_bits[i:i + 32]
        lines.append('    ' + ', '.join(str(b) for b in chunk) + ',')
    lines.append('];')
    lines.append('')

    lines.append('/// Field definitions: (offset_into_FIELD_BITS, num_bits, mask_lo, mask_hi, start_bit).')
    lines.append('/// start_bit is the lowest bit for contiguous fields; 255 for scattered fields.')
    lines.append('pub static FIELDS: [(u32, u8, u64, u64, u8); %d] = [' % len(field_defs))
    for offset, length, mask, is_contig, start in field_defs:
        lo = mask & ((1 << 64) - 1)
        hi = (mask >> 64) & ((1 << 64) - 1)
        lines.append('    (%d, %d, 0x%016x, 0x%016x, %d),' % (offset, length, lo, hi, start))
    lines.append('];')
    lines.append('')

    lines.append('/// Operand name strings, indexed by operand name ID.')
    lines.append('pub static OP_NAMES: [&str; %d] = [' % len(onc.names))
    for name in onc.names:
        lines.append('    %s,' % rust_str(name))
    lines.append('];')
    lines.append('')

    translator_ops = [
        'Pg', 'UPg', 'Pg@not', 'UPg@not', 'Ra', 'Rb', 'Rc', 'Rd', 'Sb', 'Sa',
        'URd', 'URb', 'URc', 'Pp', 'Pp@not', 'Pu', 'fmt', 'stride', 'sz', 'sp2',
        'dir', 'hilo', 'bop', 'icmp', 'Sa_bank', 'Sa_addr', 'Sb_bank', 'Sb_addr',
        'Ra_URb', 'Ra_URc', 'src_rel_sb', 'Sd', 'nPd', 'Pd',
        'Ra@negate', 'Rb@negate', 'Rc@negate', 'Ra_offset', 'URa', 'Sa_offset', 'cond',
        'num', 'mode', 'dstfmt', 'dst_wr_sb', 'SRa', 'shflmd', 'imm8', 'scaleU5',
        'satfinite', 'altfmt', 'size', 'step', 'tnspA', 'tnspB', 'srcfmt',
        'Pv', 'Sc', 'cw', 'lut', 'pop',
    ]
    lines.append('// Named constants for operand names the translator uses.')
    for name in translator_ops:
        if name in onc.by_name:
            rust_name = 'OP_' + name.upper().replace('@', '_AT_').replace('(', '_').replace(')', '_').replace(',', '_')
            lines.append('pub const %s: u16 = %d;' % (rust_name, onc.by_name[name]))
    lines.append('')

    f.write('\n'.join(lines))


def emit_classes(f, classes_75, classes_70, fc, onc):
    """Write gen/classes.rs with class info for both architectures."""
    lines = [HEADER, '']

    for tag, cl_list in [('SM75', classes_75), ('VF', classes_70)]:
        all_const_checks = []
        all_domain_checks = []
        all_domains = []
        domain_map = {}
        all_operand_entries = []
        all_reads = []
        all_writes = []
        class_structs = []

        letter_code = {'R': 0, 'U': 1, 'P': 2, 'Q': 3}

        for cl in cl_list:
            cc_offset = len(all_const_checks)
            for fid, val in cl['const_checks']:
                all_const_checks.append((fid, val))
            cc_len = len(all_const_checks) - cc_offset

            dc_offset = len(all_domain_checks)
            for fid, vals in cl['domain_checks']:
                key = tuple(vals)
                if key not in domain_map:
                    domain_map[key] = len(all_domains)
                    all_domains.append(vals)
                did = domain_map[key]
                all_domain_checks.append((fid, did))
            dc_len = len(all_domain_checks) - dc_offset

            op_offset = len(all_operand_entries)
            for nid, fid, scale, op_kind in cl['operand_entries']:
                all_operand_entries.append((nid, fid, scale, op_kind))
            op_len = len(all_operand_entries) - op_offset

            rd_offset = len(all_reads)
            for letter, nid, span in cl['reads']:
                all_reads.append((letter_code[letter], nid, span))
            rd_len = len(all_reads) - rd_offset

            wr_offset = len(all_writes)
            for letter, nid, span in cl['writes']:
                all_writes.append((letter_code[letter], nid, span))
            wr_len = len(all_writes) - wr_offset

            class_structs.append({
                'name': cl['name'],
                'mnemonic': cl['mnemonic'],
                'alternate': cl['alternate'],
                'kind_id': cl['kind_id'],
                'opcode_fid': cl['opcode_fid'],
                'opcode_value': cl['opcode_value'],
                'cc_offset': cc_offset, 'cc_len': cc_len,
                'dc_offset': dc_offset, 'dc_len': dc_len,
                'op_offset': op_offset, 'op_len': op_len,
                'rd_offset': rd_offset, 'rd_len': rd_len,
                'wr_offset': wr_offset, 'wr_len': wr_len,
                'unused_mask': cl['unused_mask'],
            })

        lines.append('// --- %s classes ---' % tag)
        lines.append('')

        lines.append('pub static %s_CONST_CHECKS: [(u16, u32); %d] = [' % (tag, len(all_const_checks)))
        for fid, val in all_const_checks:
            lines.append('    (%d, %d),' % (fid, val))
        lines.append('];')
        lines.append('')

        lines.append('pub static %s_DOMAIN_CHECKS: [(u16, u16); %d] = [' % (tag, len(all_domain_checks)))
        for fid, did in all_domain_checks:
            lines.append('    (%d, %d),' % (fid, did))
        lines.append('];')
        lines.append('')

        flat_domains = []
        domain_offsets = []
        for vals in all_domains:
            domain_offsets.append((len(flat_domains), len(vals)))
            flat_domains.extend(vals)
        lines.append('pub static %s_DOMAIN_VALUES: [u32; %d] = [' % (tag, len(flat_domains)))
        for i in range(0, len(flat_domains), 16):
            chunk = flat_domains[i:i + 16]
            lines.append('    ' + ', '.join(str(v) for v in chunk) + ',')
        lines.append('];')
        lines.append('')

        lines.append('pub static %s_DOMAIN_OFFSETS: [(u32, u16); %d] = [' % (tag, len(domain_offsets)))
        for off, length in domain_offsets:
            lines.append('    (%d, %d),' % (off, length))
        lines.append('];')
        lines.append('')

        lines.append('pub static %s_OPERANDS: [(u16, u16, u16, u8); %d] = [' % (tag, len(all_operand_entries)))
        for nid, fid, scale, op_kind in all_operand_entries:
            lines.append('    (%d, %d, %d, %d),' % (nid, fid, scale, op_kind))
        lines.append('];')
        lines.append('')

        lines.append('/// (letter, operand, registers: the number, or 0x8000 + a table of SPAN_TABLES).')
        lines.append('pub static %s_READS: [(u8, u16, u16); %d] = [' % (tag, len(all_reads)))
        for lc, nid, span in all_reads:
            lines.append('    (%d, %d, %d),' % (lc, nid, span))
        lines.append('];')
        lines.append('')

        lines.append('pub static %s_WRITES: [(u8, u16, u16); %d] = [' % (tag, len(all_writes)))
        for lc, nid, span in all_writes:
            lines.append('    (%d, %d, %d),' % (lc, nid, span))
        lines.append('];')
        lines.append('')

        # Class info: store name and mnemonic as &str directly in the tuple.
        # (name, mnemonic, alternate, kind, opcode_fid, opcode_value,
        #  cc_off, cc_len, dc_off, dc_len, op_off, op_len,
        #  rd_off, rd_len, wr_off, wr_len, unused_mask_lo, unused_mask_hi)
        lines.append('#[allow(clippy::type_complexity)]')
        lines.append('pub static %s_CLASSES: [(&str, &str, bool, u8, u16, u16, u16, u16, u16, u16, u16, u16, u16, u16, u16, u16, u64, u64); %d] = [' % (tag, len(class_structs)))
        for cs in class_structs:
            lo = cs['unused_mask'] & ((1 << 64) - 1)
            hi = (cs['unused_mask'] >> 64) & ((1 << 64) - 1)
            lines.append('    (%s, %s, %s, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, 0x%016x, 0x%016x),' % (
                rust_str(cs['name']), rust_str(cs['mnemonic']),
                'true' if cs['alternate'] else 'false', cs['kind_id'],
                cs['opcode_fid'], cs['opcode_value'],
                cs['cc_offset'], cs['cc_len'], cs['dc_offset'], cs['dc_len'],
                cs['op_offset'], cs['op_len'], cs['rd_offset'], cs['rd_len'], cs['wr_offset'], cs['wr_len'],
                lo, hi,
            ))
        lines.append('];')
        lines.append('')

    # Opcode lookup tables
    for tag, cl_list in [('SM75', classes_75), ('VF', classes_70)]:
        by_opcode = collections.defaultdict(list)
        for i, cl in enumerate(cl_list):
            by_opcode[(cl['opcode_fid'], cl['opcode_value'])].append(i)

        by_field = collections.defaultdict(dict)
        for (fid, oval), indices in by_opcode.items():
            by_field[fid][oval] = indices

        for fid, oval_map in sorted(by_field.items()):
            max_oval = max(oval_map.keys()) + 1
            flat = []
            offsets = []
            for oval in range(max_oval):
                indices = oval_map.get(oval, [])
                offsets.append((len(flat), len(indices)))
                flat.extend(indices)

            lines.append('/// Opcode lookup for %s, field %d: [opcode_value] -> (offset, count) into CANDIDATES' % (tag, fid))
            lines.append('pub static %s_OPCODE_%d_OFFSETS: [(u32, u16); %d] = [' % (tag, fid, len(offsets)))
            for off, cnt in offsets:
                lines.append('    (%d, %d),' % (off, cnt))
            lines.append('];')
            lines.append('')

            lines.append('pub static %s_OPCODE_%d_CANDIDATES: [u16; %d] = [' % (tag, fid, len(flat)))
            for i in range(0, len(flat), 20):
                chunk = flat[i:i + 20]
                lines.append('    ' + ', '.join(str(v) for v in chunk) + ',')
            lines.append('];')
            lines.append('')

    # Numbers of registers that depend on the instruction.
    keys, values, tables = [], [], []
    for table_keys, table_values in SPANS.tables:
        tables.append((len(keys), len(table_keys), len(values)))
        keys += table_keys
        values += table_values
    lines.append('/// How many registers an operand takes when that depends on the instruction (a 64-bit address,')
    lines.append('/// a load of 4, 8 or 16 bytes): (first of its keys in SPAN_KEYS, how many, first of its values in')
    lines.append('/// SPAN_VALUES). The values are indexed by the values of the key operands, the first in the')
    lines.append('/// upper bits.')
    lines.append('pub static SPAN_TABLES: [(u16, u8, u32); %d] = [' % len(tables))
    for row in tables:
        lines.append('    (%d, %d, %d),' % row)
    lines.append('];')
    lines.append('')
    lines.append('/// (operand name, bits of its field).')
    lines.append('pub static SPAN_KEYS: [(u16, u8); %d] = [' % len(keys))
    for row in keys:
        lines.append('    (%d, %d),' % row)
    lines.append('];')
    lines.append('')
    lines.append('pub static SPAN_VALUES: [u8; %d] = [' % len(values))
    for i in range(0, len(values), 32):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + 32]) + ',')
    lines.append('];')
    lines.append('')

    f.write('\n'.join(lines))


def emit_rules(f, mc, fc, onc, classes_75):
    """Write gen/rules.rs with rule data."""
    lines = [HEADER, '']

    name75_to_id = {cl['name']: i for i, cl in enumerate(classes_75)}

    # rule_of map
    lines.append('/// rule_of: (sm75_class_id, sm70_class_name) for each rule in rules-sm75.tsv.')
    lines.append('pub static RULE_OF: [(u16, &str); %d] = [' % len(mc.rule_of))
    for sm75_name, sm70_name in mc.rule_of.items():
        if sm75_name in name75_to_id:
            lines.append('    (%d, %s),' % (name75_to_id[sm75_name], rust_str(sm70_name)))
    lines.append('];')
    lines.append('')

    # Pre-computed rules
    all_rules = []

    for sm75_name, sm70_name in mc.rule_of.items():
        r = analyze_rule(mc, fc, onc, sm75_name, sm70_name)
        if r is not None:
            all_rules.append(r)

    # Memory instructions whose address has a uniform part: the rule to the plain instruction, without
    # what `uniform_address` deals with itself (in shared memory the register may have a stride).
    for prefix, plain in MC.UNIFORM_ADDRESS.items():
        for c in mc.md75.classes:
            if c.name.startswith(prefix):
                part = 'Ra_URb' if 'Ra_URb' in c.operands else 'Ra_URc'
                r = analyze_rule(mc, fc, onc, c.name, plain, (part, 'stride', 'Ra') if plain in MC.SHARED else (part, 'sp2', 'TABLE', 'Ra'))
                if r is not None:
                    all_rules.append(r)

    for c in mc.md75.classes:
        if c.name.startswith('imad_hi__'):
            suffix = c.name[len('imad_hi__'):]
            target = 'imad_wide__' + suffix.replace('RUR_RUR', 'RRR_RRR')
            r = analyze_rule(mc, fc, onc, c.name, target)
            if r is not None:
                all_rules.append(r)

    seen = set()
    unique_rules = []
    for r in all_rules:
        key = (r['sm75_name'], r['sm70_name'], r['drop_tuple'])
        if key not in seen:
            seen.add(key)
            unique_rules.append(r)
    all_rules = unique_rules

    all_moves = []
    all_allowed = []
    all_allowed_values = []
    allowed_domain_map = {}
    all_dropped = []

    rule_structs = []
    for r in all_rules:
        moves_offset = len(all_moves)
        for src_fids, dst_fids, conv in r['moves']:
            assert len(src_fids) == len(dst_fids), (r['sm75_name'], r['sm70_name'])
            for sf, df in zip(src_fids, dst_fids):
                all_moves.append((sf, df, conv))
        moves_len = len(all_moves) - moves_offset

        allowed_offset = len(all_allowed)
        for fid, vals in r['allowed']:
            key = tuple(vals)
            if key not in allowed_domain_map:
                allowed_domain_map[key] = len(all_allowed_values)
                all_allowed_values.extend(vals)
                all_allowed_values.append(0xFFFFFFFF)
            all_allowed.append((fid, allowed_domain_map[key]))
        allowed_len = len(all_allowed) - allowed_offset

        dropped_offset = len(all_dropped)
        for key, fids in r['dropped'].items():
            for fid in fids:
                all_dropped.append((key, fid))
        dropped_len = len(all_dropped) - dropped_offset

        rule_structs.append({
            'sm75_name': r['sm75_name'],
            'sm70_name': r['sm70_name'],
            'fixed': r['fixed'],
            'moves_offset': moves_offset,
            'moves_len': moves_len,
            'allowed_offset': allowed_offset,
            'allowed_len': allowed_len,
            'dropped_offset': dropped_offset,
            'dropped_len': dropped_len,
            'drop_tuple': r['drop_tuple'],
        })

    lines.append('/// Rule moves: (src_field_id, dst_field_id, conv).')
    lines.append('/// conv: 0=raw, 1=register (uniform->ordinary), 2=predicate (uniform->ordinary), 3=a signed number into a wider field.')
    lines.append('pub static RULE_MOVES: [(u16, u16, u8); %d] = [' % len(all_moves))
    for sf, df, conv in all_moves:
        lines.append('    (%d, %d, %d),' % (sf, df, conv))
    lines.append('];')
    lines.append('')

    lines.append('pub static RULE_ALLOWED: [(u16, u32); %d] = [' % len(all_allowed))
    for fid, doff in all_allowed:
        lines.append('    (%d, %d),' % (fid, doff))
    lines.append('];')
    lines.append('')

    lines.append('pub static RULE_ALLOWED_VALUES: [u32; %d] = [' % len(all_allowed_values))
    for i in range(0, len(all_allowed_values), 16):
        chunk = all_allowed_values[i:i + 16]
        lines.append('    ' + ', '.join('0x%x' % v for v in chunk) + ',')
    lines.append('];')
    lines.append('')

    lines.append('pub static RULE_DROPPED: [(&str, u16); %d] = [' % len(all_dropped))
    for key, fid in all_dropped:
        lines.append('    (%s, %d),' % (rust_str(key), fid))
    lines.append('];')
    lines.append('')

    lines.append('/// Pre-computed rules.')
    lines.append('/// (sm75_name, sm70_name, fixed_lo, fixed_hi, moves_off, moves_len, allowed_off, allowed_len, dropped_off, dropped_len, drop_key)')
    lines.append('#[allow(clippy::type_complexity)]')
    lines.append('pub static RULES: [(&str, &str, u64, u64, u16, u16, u16, u16, u16, u16, &str); %d] = [' % len(rule_structs))
    for rs in rule_structs:
        lo = rs['fixed'] & ((1 << 64) - 1)
        hi = (rs['fixed'] >> 64) & ((1 << 64) - 1)
        drop_key = ','.join(rs['drop_tuple']) if rs['drop_tuple'] else ''
        lines.append('    (%s, %s, 0x%016x, 0x%016x, %d, %d, %d, %d, %d, %d, %s),' % (
            rust_str(rs['sm75_name']), rust_str(rs['sm70_name']), lo, hi,
            rs['moves_offset'], rs['moves_len'],
            rs['allowed_offset'], rs['allowed_len'],
            rs['dropped_offset'], rs['dropped_len'],
            rust_str(drop_key),
        ))
    lines.append('];')
    lines.append('')

    f.write('\n'.join(lines))


def emit_assembly(f, mc, fc, onc):
    """Write gen/assembly.rs with assembly templates."""
    lines = [HEADER, '']

    ASM_CLASSES = [
        'mov__RRR_RR', 'isetp__RRR_RR', 'sel__RRR_RRR',
        'isetp__RsIR_RI', 'sel__RuIR_RIR',
        'isetp__RCR_RC', 'sel__RCR_RCR',
        'shf__RuIR_RIR', 'mov__RCR_RC',
        'imad_wide__RsIR_RIR', 'iadd3_noimm__RRR_RRR',
        'exit_', 'nop_', 'ldc__RaNonRZ', 'imad__RsIR_RIR',
        'p2r__RsIR_RIR', 'r2p__RIR',
        's2r_', 'shfl__RRI', 'shfl__RII', 'lds__sImmOffset',
        'iadd3_imm__RsIR_RIR', 'lea_lo_noimm__RRR_RRR', 'ldl__sImmOffset', 'stl__sImmOffset',
        'lop3_lut__RuIR_RIR', 'lop3_lut__RRR_RRR',
        'hmma__884_f32', 'hmma__884_f16_f16',
    ]
    if 'bpt__TRAP' in mc.md70.by_name:
        ASM_CLASSES.append('bpt__TRAP')

    for c in mc.md70.classes:
        if c.name.startswith('imad_wide__') and c.name not in ASM_CLASSES:
            ASM_CLASSES.append(c.name)

    ASM_CLASSES.extend(['ldg__sImmOffset', 'stg__sImmOffset', 'f2f_f32_downconvert__RRR_RRR', 'prmt__RuIR_RIR'])

    templates = []
    all_setters = []
    all_enum_entries = []
    all_attr_setters = []
    enum_map = {}

    for class_name in ASM_CLASSES:
        asm = analyze_assembly(mc, fc, onc, class_name)
        if asm is None:
            continue

        setter_offset = len(all_setters)
        for nid, fid, scale, enum_values, default, orig_name in asm['setters']:
            if enum_values:
                key = tuple(sorted(enum_values.items()))
                if key not in enum_map:
                    enum_map[key] = len(all_enum_entries)
                    for s, v in sorted(enum_values.items()):
                        all_enum_entries.append((s, v))
                    all_enum_entries.append(('', 0xFFFFFFFF))
                ee_offset = enum_map[key]
            else:
                ee_offset = 0xFFFFFFFF
            all_setters.append((nid, fid, scale, default, ee_offset))
        setter_len = len(all_setters) - setter_offset

        attr_offset = len(all_attr_setters)
        for key, fid in asm['attr_setters']:
            all_attr_setters.append((key, fid))
        attr_len = len(all_attr_setters) - attr_offset

        templates.append({
            'name': class_name,
            'base_word': asm['base_word'],
            'setter_offset': setter_offset,
            'setter_len': setter_len,
            'attr_offset': attr_offset,
            'attr_len': attr_len,
        })

    lines.append('/// Assembly setters: (name_id, field_id, scale, default_value, enum_entries_offset).')
    lines.append('/// enum_entries_offset is 0xFFFFFFFF when the operand is not an enum.')
    lines.append('pub static ASM_SETTERS: [(u16, u16, u16, u32, u32); %d] = [' % len(all_setters))
    for nid, fid, scale, default, ee_offset in all_setters:
        lines.append('    (%d, %d, %d, %d, 0x%x),' % (nid, fid, scale, default, ee_offset))
    lines.append('];')
    lines.append('')

    lines.append('pub static ASM_ENUM_ENTRIES: [(&str, u32); %d] = [' % len(all_enum_entries))
    for s, v in all_enum_entries:
        lines.append('    (%s, 0x%x),' % (rust_str(s), v & 0xFFFFFFFF))
    lines.append('];')
    lines.append('')

    lines.append('pub static ASM_ATTR_SETTERS: [(&str, u16); %d] = [' % len(all_attr_setters))
    for key, fid in all_attr_setters:
        lines.append('    (%s, %d),' % (rust_str(key), fid))
    lines.append('];')
    lines.append('')

    lines.append('/// Assembly templates: (name, base_lo, base_hi, setter_off, setter_len, attr_off, attr_len).')
    lines.append('#[allow(clippy::type_complexity)]')
    lines.append('pub static ASM_TEMPLATES: [(&str, u64, u64, u16, u16, u16, u16); %d] = [' % len(templates))
    for t in templates:
        lo = t['base_word'] & ((1 << 64) - 1)
        hi = (t['base_word'] >> 64) & ((1 << 64) - 1)
        lines.append('    (%s, 0x%016x, 0x%016x, %d, %d, %d, %d),' % (
            rust_str(t['name']), lo, hi, t['setter_offset'], t['setter_len'],
            t['attr_offset'], t['attr_len']))
    lines.append('];')
    lines.append('')

    f.write('\n'.join(lines))


